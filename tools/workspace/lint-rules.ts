import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { format } from "vite-plus/fmt";

const root = resolve(import.meta.dirname, "../..");
const catalogSource = readFileSync(
  resolve(root, "crates/diagnostics/src/lint/config/catalog.rs"),
  "utf8",
);
const policySource = readFileSync(
  resolve(root, "crates/diagnostics/src/lint/config/policies.rs"),
  "utf8",
);
const presetSource = readFileSync(
  resolve(root, "crates/diagnostics/src/lint/config/presets.rs"),
  "utf8",
);
const catalog = catalogSource.split("define_lint_rules! {")[1].split("\n}")[0];
const lengthUnits = [
  ...readFileSync(resolve(root, "crates/css/src/values/policy.rs"), "utf8")
    .split("pub fn is_length_unit(")[1]
    .split("\n}")[0]
    .matchAll(/"([a-z]+)"/g),
].map((match) => match[1]);
const optionTypes: Record<string, string> = Object.fromEntries(
  [
    ...catalogSource
      .split("macro_rules! lint_config_type {")[1]
      .split("macro_rules! lint_config_value")[0]
      .matchAll(/\((\w+)\) => \{\s*(\w+)Config\s*\};/g),
  ].map(([, variant, type]) => [variant, type]),
);
const camel = (value: string) =>
  value.replace(/[-_]([a-z])/g, (_, letter: string) => letter.toUpperCase());
const defaultSource = catalogSource.split("macro_rules! lint_config_value {")[1];
const rootFontSizeDefault = Number(/DEFAULT: Self = Self\(([\d.]+)\)/.exec(policySource)?.[1]);
if (!Number.isFinite(rootFontSizeDefault) || rootFontSizeDefault <= 0) {
  throw new Error("Cannot read the default root font size from the Rust lint policies");
}
const rules = [...catalog.matchAll(/(\w+) => "([\w-]+)",/g)].map(([, variant, name]) => {
  const optionType = optionTypes[variant];
  const fields = optionType
    ? [
        ...policySource
          .split(`pub struct ${optionType}Config {`)[1]
          .split("\n}")[0]
          .matchAll(/pub (\w+):/g),
      ].map((field) => camel(field[1]))
    : undefined;
  const defaults = optionType
    ? Object.fromEntries(
        [
          ...defaultSource
            .split(`(${variant}, $severity:expr) => {`)[1]
            .split("\n    };")[0]
            .matchAll(/(\w+): (\$severity|Vec::new\(\)|RootFontSize::DEFAULT|true|false),/g),
        ].map(([, field, value]) => [
          camel(field),
          value === "$severity"
            ? "warn"
            : value === "Vec::new()"
              ? []
              : value === "RootFontSize::DEFAULT"
                ? rootFontSizeDefault
                : value === "true",
        ]),
      )
    : undefined;
  if (fields?.some((field) => defaults?.[field] === undefined)) {
    throw new Error(`Cannot read default options for ${name}`);
  }
  return {
    variant,
    name,
    nativeName: camel(name),
    field: name.replaceAll("-", "_"),
    optionType,
    fields,
    defaults,
  };
});

function presetEntries(name: string) {
  return Object.fromEntries(
    [
      ...presetSource
        .split(`const ${name}:`)[1]
        .split("];")[0]
        .matchAll(/\(\s*LintKind::(\w+),\s*LintSeverity::(\w+)\s*,?\s*\)/g),
    ].map(([, variant, severity]) => {
      const rule = rules.find((rule) => rule.variant === variant);
      if (!rule) {
        throw new Error(`Unknown preset rule: ${variant}`);
      }
      return [rule.name, severity.toLowerCase()];
    }),
  );
}

const recommended = presetEntries("RECOMMENDED");
const stylistic = presetEntries("STYLISTIC");
const strictAdditions = presetEntries("STRICT_ADDITIONS");

async function output(file: string, source: string) {
  const path = resolve(root, file);
  const content = file.endsWith(".rs")
    ? execFileSync("rustfmt", ["--emit", "stdout", "--edition", "2024"], {
        input: source,
        encoding: "utf8",
      }).replaceAll("\r\n", "\n")
    : (await format(path, source)).code;
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== content) {
      throw new Error(`Generated lint configuration differs: ${file}`);
    }
  } else {
    writeFileSync(path, content);
  }
}

await output(
  "packages/config/src/lint-rules.ts",
  `// Generated by tools/workspace/lint-rules.ts from the Rust lint catalog.

/**
 * Maps public rule IDs to native option names and default detection settings.
 * Each entry's nativeName identifies its field in the compiler binding. Null options indicate
 * a severity-only rule. Other entries list accepted fields in options and initial values in defaults.
 * Treat these shared catalog entries as readonly.
 */
export const lintRules = ${JSON.stringify(
    Object.fromEntries(
      rules.map((rule) => [
        rule.name,
        {
          nativeName: rule.nativeName,
          defaults: rule.defaults ?? null,
          options: rule.fields ?? null,
        },
      ]),
    ),
    null,
    2,
  )} as const;

/** Lowercase CSS length units accepted by lint validation, which also accepts case variations. */
export const lengthUnits = ${JSON.stringify(lengthUnits)} as const;

/** Public kebab-case rule IDs used as keys in lint configuration. */
export type LintRule = keyof typeof lintRules;

/** Rules that accept only a severity string because their catalog entries have no option fields. */
export type SimpleLintRule = {
  [K in LintRule]: (typeof lintRules)[K]["options"] extends null ? K : never;
}[LintRule];
`,
);

await output(
  "packages/config/src/lint-presets.ts",
  `// Generated by tools/workspace/lint-rules.ts from the Rust lint presets.

/** Default checks also inherited by the strict preset. The same object is shared by all consumers. */
const recommended = {
  name: "stillwind/recommended",
  rules: ${JSON.stringify(recommended)},
} as const;

/**
 * Built-in lint policies for ordered preset composition. Treat their shared objects as readonly.
 * Recommended supplies the omitted-lint default. Strict denies every recommended rule and adds
 * further denied checks. Stylistic enables optional rewrites and utility sorting.
 */
export const lintPresets = {
  recommended,
  strict: {
    name: "stillwind/strict",
    extends: [recommended],
    rules: ${JSON.stringify({
      ...Object.fromEntries(Object.keys(recommended).map((name) => [name, "deny"])),
      ...strictAdditions,
    })},
  },
  stylistic: {
    name: "stillwind/stylistic",
    rules: ${JSON.stringify(stylistic)},
  },
} as const;
`,
);

const detailed = rules.filter((rule) => rule.optionType);
await output(
  "crates/napi/src/options/lint.rs",
  `//! Generated by tools/workspace/lint-rules.ts from the Rust lint catalog.

use napi::Error;
use napi_derive::napi;

use stillwind_diagnostics::LintOverrides;

use super::{lint_severity, ${detailed.map((rule) => `Native${rule.optionType}Options`).join(", ")}};

/// Lint settings applied to compiler defaults.
#[napi(object)]
pub struct NativeLintOptions {
${rules
  .map(
    (rule) => `    /// Settings for \`${rule.name}\`.
    pub ${rule.field}: Option<${rule.optionType ? `Native${rule.optionType}Options` : "String"}>,`,
  )
  .join("\n")}
}

impl TryFrom<NativeLintOptions> for LintOverrides {
    type Error = Error;

    #[allow(clippy::too_many_lines)]
    fn try_from(input: NativeLintOptions) -> napi::Result<Self> {
        Ok(Self {
${rules.map((rule) => `            ${rule.field}: input.${rule.field}.map(${rule.optionType ? "TryInto::try_into" : "|value| lint_severity(&value)"}).transpose()?,`).join("\n")}
        })
    }
}
`,
);
