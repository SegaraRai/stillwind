import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { format } from "vite-plus/fmt";

const root = resolve(import.meta.dirname, "../..");
const source = readFileSync(resolve(root, "crates/diagnostics/src/lint/config.rs"), "utf8");
const catalog = source.split("define_lint_rules! {")[1].split("\n}")[0];
const lengthUnits = [
  ...readFileSync(resolve(root, "crates/css/src/values/policy.rs"), "utf8")
    .split("pub fn is_length_unit(")[1]
    .split("\n}")[0]
    .matchAll(/"([a-z]+)"/g),
].map((match) => match[1]);
const optionTypes: Record<string, string> = Object.fromEntries(
  [
    ...source
      .split("macro_rules! lint_config_type {")[1]
      .split("macro_rules! lint_config_value")[0]
      .matchAll(/\((\w+)\) => \{\s*(\w+)Config\s*\};/g),
  ].map(([, variant, type]) => [variant, type]),
);
const camel = (value: string) =>
  value.replace(/[-_]([a-z])/g, (_, letter: string) => letter.toUpperCase());
const rules = [...catalog.matchAll(/(\w+) => \("([\w-]+)", (.*?)\),/g)].map(
  ([, variant, name, severity]) => {
    const optionType = optionTypes[variant];
    const fields = optionType
      ? [
          ...source
            .split(`pub struct ${optionType}Config {`)[1]
            .split("\n}")[0]
            .matchAll(/pub (\w+):/g),
        ].map((field) => camel(field[1]))
      : undefined;
    return {
      variant,
      name,
      nativeName: camel(name),
      field: name.replaceAll("-", "_"),
      optionType,
      fields,
      severity: /LintSeverity::(\w+)/.exec(severity)?.[1].toLowerCase(),
    };
  },
);

async function output(file: string, source: string) {
  const path = resolve(root, file);
  const content = file.endsWith(".rs")
    ? execFileSync("rustfmt", ["--emit", "stdout", "--edition", "2024"], {
        input: source,
        encoding: "utf8",
      }).replaceAll("\r\n", "\n")
    : (await format(path, source)).code;
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== content) {
      throw new Error(`Generated lint configuration differs: ${file}`);
    }
  } else {
    writeFileSync(path, content);
  }
}

await output(
  "packages/config/src/lint-rules.ts",
  `// Generated by tools/workspace/lint-rules.ts from the Rust lint catalog.

export const lintRules = ${JSON.stringify(
    Object.fromEntries(
      rules.map((rule) => [
        rule.name,
        {
          nativeName: rule.nativeName,
          severity: rule.severity ?? null,
          options: rule.fields ?? null,
        },
      ]),
    ),
    null,
    2,
  )} as const;

export const lengthUnits = ${JSON.stringify(lengthUnits)} as const;

export type LintRule = keyof typeof lintRules;

export type SimpleLintRule = {
  [K in LintRule]: (typeof lintRules)[K]["options"] extends null ? K : never;
}[LintRule];
`,
);

const detailed = rules.filter((rule) => rule.optionType);
await output(
  "crates/napi/src/options/lint.rs",
  `//! Generated by tools/workspace/lint-rules.ts from the Rust lint catalog.

use napi::Error;
use napi_derive::napi;

use stillwind_diagnostics::LintOverrides;

use super::{lint_severity, ${detailed.map((rule) => `Native${rule.optionType}Options`).join(", ")}};

/// Lint settings applied to compiler defaults.
#[napi(object)]
pub struct NativeLintOptions {
${rules
  .map(
    (rule) => `    /// Settings for \`${rule.name}\`.
    pub ${rule.field}: Option<${rule.optionType ? `Native${rule.optionType}Options` : "String"}>,`,
  )
  .join("\n")}
}

impl TryFrom<NativeLintOptions> for LintOverrides {
    type Error = Error;

    #[allow(clippy::too_many_lines)]
    fn try_from(input: NativeLintOptions) -> napi::Result<Self> {
        Ok(Self {
${rules.map((rule) => `            ${rule.field}: input.${rule.field}.map(${rule.optionType ? "TryInto::try_into" : "|value| lint_severity(&value)"}).transpose()?,`).join("\n")}
        })
    }
}
`,
);
