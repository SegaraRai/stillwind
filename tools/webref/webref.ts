import { readFile, writeFile } from "node:fs/promises";
import { parseArgs } from "node:util";

import webref from "@webref/css/css.json" with { type: "json" };
import webrefPackageJson from "@webref/css/package.json" with { type: "json" };

type CssProperty = (typeof webref)["properties"][number];

const destination = new URL("../../crates/css/assets/webref-properties.rs", import.meta.url);
const {
  values: { check },
} = parseArgs({
  options: {
    check: {
      type: "boolean",
      default: false,
    },
  },
});

function rustString(value: string): string {
  return JSON.stringify(value);
}

function rustSlice(values: readonly string[] | undefined): string {
  return `&[${(values ?? []).map(rustString).join(", ")}]`;
}

function rustOption(value: string | undefined): string {
  return value === undefined ? "None" : `Some(${rustString(value)})`;
}

function render(properties: readonly CssProperty[]): string {
  const definitions = properties
    .filter((property) => property.syntax)
    .sort((left, right) => left.name.localeCompare(right.name))
    .map(
      (property) =>
        `    WebrefPropertySyntax { name: ${rustString(property.name)}, syntax: ${rustString(property.syntax!)}, longhands: ${rustSlice(property.longhands)}, logical_group: ${rustOption(property.logicalPropertyGroup)}, href: ${rustString(property.href)} },`,
    );
  return [
    "// @generated by tools/webref/webref.ts; DO NOT EDIT.",
    `// Source: @webref/css/css.json ${webrefPackageJson.version} (CSSWG Web Living Standards).`,
    "",
    "pub(crate) const WEBREF_PROPERTIES: &[WebrefPropertySyntax] = &[",
    ...definitions,
    "];",
    "",
  ].join("\n");
}

const generated = render(webref.properties);

if (check) {
  const current = await readFile(destination, "utf8");
  if (current.replaceAll("\r\n", "\n") !== generated) {
    throw new Error("Webref CSS domain snapshot is stale; run vp run generate:webref");
  }
} else {
  await writeFile(destination, generated);
}
