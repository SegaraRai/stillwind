import {
  fixtureSupport,
  failureReason,
  type Fixture,
  type FixtureManifest,
  type SupportTier,
  type ExpectedFailure,
} from "./fixture.ts";
import { contractPolicy } from "./policy.ts";

/** Parses package names and runner options; rejects unsupported options and support tiers. */
export function matrixOptions(args: string[]) {
  const options: {
    selected: string[];
    support?: SupportTier;
    typecheck: boolean;
    list: boolean;
    docs: boolean;
  } = {
    selected: [],
    typecheck: false,
    list: false,
    docs: false,
  };
  for (let index = 0; index < args.length; index++) {
    const arg = args[index]!;
    if (arg === "--support") {
      const tier = args[++index];
      if (tier !== "primary" && tier !== "compatibility") {
        throw new Error("--support requires primary or compatibility");
      }
      options.support = tier;
    } else if (arg === "--typecheck") {
      options.typecheck = true;
    } else if (arg === "--list") {
      options.list = true;
    } else if (arg === "--write-support-doc") {
      options.docs = true;
    } else if (arg.startsWith("--")) {
      throw new Error(`Unknown matrix option: ${arg}`);
    } else {
      options.selected.push(arg);
    }
  }
  return options;
}

/** Returns profiles matching both selectors. Packages without a manifest contain independent CSS contracts. */
export function selectedProfiles(
  manifest: FixtureManifest,
  support?: SupportTier,
  profile?: string,
) {
  if (profile && !manifest.profiles.includes(profile)) {
    throw new Error(`Unknown profile ${profile} for ${manifest.id}`);
  }
  return manifest.profiles.filter(
    (name) =>
      (!profile || profile === name) && (!support || fixtureSupport(manifest, name) === support),
  );
}

/** Produces a deterministic support inventory from manifests, including profile overrides and known map limitations. */
export function supportDocument(
  manifests: (FixtureManifest & Partial<Pick<Fixture, "sourceMaps" | "edits">>)[],
) {
  const rows = manifests.flatMap((manifest) =>
    manifest.profiles.map(
      (profile) => `| ${manifest.id} | ${profile} | ${fixtureSupport(manifest, profile)} |`,
    ),
  );
  const escape = (text: string) => text.replaceAll("|", "\\|").replaceAll("\n", " ");
  const limitations = manifests.flatMap((manifest) =>
    manifest.profiles.flatMap((profile) => {
      const rows: string[] = [];
      const add = (contract: string, target: string, failure?: ExpectedFailure) => {
        if (failure) {
          rows.push(
            `| ${manifest.id} | ${profile} | ${contract} | ${escape(target)} | ${escape(failureReason(failure))}${failure.issue ? ` ([issue](${failure.issue}))` : ""} |`,
          );
        }
      };
      for (const map of manifest.sourceMaps ?? []) {
        add(
          "sourceMaps (development)",
          `${map.file}: ${map.macro}`,
          map.development?.expectedFailure,
        );
        const failure = map.expectedFailure;
        add(
          "sourceMaps (production)",
          `${map.file}: ${map.macro}`,
          failure && ("reason" in failure ? (failure as ExpectedFailure) : failure[profile]),
        );
      }
      for (const [name, edit] of Object.entries(manifest.edits ?? {})) {
        add("sourceUpdate", name, edit.expectedFailure);
      }
      return rows;
    }),
  );
  return `# Support inventory

Generated by \`vp exec node e2e/harness/src/matrix.ts --write-support-doc\`. Edit fixture manifests to change classifications.

Primary combinations receive priority for ordinary CSS rendering, updates and SSR. Compatibility combinations remain in the full matrix with explicit limitations. Contract priorities are independent of these classifications. Framework-independent CSS tests run with either selection.

| Fixture | Profile | Support |
| --- | --- | --- |
${rows.join("\n")}

## Contract priorities

| Contract | Priority | Guarantee |
| --- | --- | --- |
${Object.entries(contractPolicy)
  .map(([id, policy]) => `| ${id} | ${policy.priority} | ${policy.description} |`)
  .join("\n")}

## Expected failures

Each declaration keeps its original assertion. An unexpected pass fails the test. Production declarations run in both cold and warm builds.

| Fixture | Profile | Contract | Target | Reason |
| --- | --- | --- | --- | --- |
${limitations.join("\n")}
`;
}
