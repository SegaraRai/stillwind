pub(crate) fn render_react_types(theme: &stillwind_css::ThemeIndex) -> String {
    let mut utilities = Vec::new();
    if theme.imports.builtins {
        utilities.extend(stillwind_tailwind::builtin_utility_names());
        for token in &theme.tokens {
            let Some((namespace, name)) = token.name.value.trim_start_matches("--").split_once('-')
            else {
                continue;
            };
            for (prefix, expected_namespace) in stillwind_tailwind::builtin_utility_token_prefixes()
            {
                if namespace == expected_namespace {
                    utilities.push(format!("{prefix}-{name}"));
                }
            }
        }
    }
    utilities.sort();
    utilities.dedup();
    let entries = utilities
        .into_iter()
        .map(|utility| format!("    \"{utility}\": true;"))
        .collect::<Vec<_>>()
        .join("\n");
    let mut variants = Vec::new();
    if theme.imports.builtins {
        variants.extend(stillwind_tailwind::builtin_variant_names());
        variants.extend(theme.tokens.iter().filter_map(|token| {
            if let stillwind_css::ThemeTokenKind::Token {
                namespace: stillwind_css::ThemeNamespace::Breakpoint,
                name,
            } = &token.kind
            {
                Some(name.clone())
            } else {
                None
            }
        }));
    }
    variants.sort_unstable();
    variants.dedup();
    let variants = variants
        .into_iter()
        .map(|variant| format!("    \"{variant}\": true;"))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "// Generated by Stillwind from @theme. Do not edit.\nimport \"stillwind/react\";\n\ndeclare module \"stillwind/react\" {{\n  interface StillwindUtilityVocabulary {{\n{entries}\n  }}\n  interface StillwindVariantVocabulary {{\n{variants}\n  }}\n}}\n\nexport {{}};\n"
    )
}

pub(crate) fn class_name(canonical_input: &str) -> String {
    let hash = blake3::hash(canonical_input.as_bytes());
    format!("_s_{}", &hash.to_hex()[..8])
}
