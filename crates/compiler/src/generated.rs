//! JavaScript text composition with expression-level source provenance.
//!
//! Build source-owned fragments with [`Code::source`], synthetic fragments through
//! `From<LeanString>` or `From<&str>`, and concatenate them with [`Code::join`] or
//! [`code!`]. [`js_string`] quotes decoded string values. This module preserves
//! relative byte ranges; transform rendering validates them and converts to UTF-16.
//! It neither parses JavaScript nor performs HTML attribute encoding.

use lean_string::{LeanStr, LeanString, ToLeanString};

use stillwind_source::Span;

use crate::transforms::ExpressionMapping;

/// A generated fragment carrying the original locations of retained expressions.
///
/// Concatenation changes generated offsets only. Distinct occurrences keep distinct
/// origins even when their text is identical or their source order is reversed.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub(crate) struct Code {
    /// Generated UTF-8 text, including syntax with no exact source counterpart.
    pub(crate) text: LeanString,
    /// Nonempty, nonoverlapping ranges ordered by generated byte offset within `text`.
    /// Original spans may be repeated or out of order; gaps are synthetic text.
    pub(crate) mappings: Vec<ExpressionMapping>,
}

impl Code {
    /// Marks the entire fragment as one exact source occurrence.
    ///
    /// `text` must be nonempty and equal the original buffer slice at `original`.
    /// Construction does not validate that contract; transform rendering does.
    pub(crate) fn source(text: LeanString, original: Span) -> Self {
        let end = text.len();
        Self {
            text,
            mappings: vec![ExpressionMapping {
                start: 0,
                end,
                original,
                exact: true,
            }],
        }
    }

    /// Concatenates fragments in iterator order, placing synthetic separators between them.
    ///
    /// Child mappings must satisfy the `Code` invariants. Their generated offsets are
    /// rebased into the result without changing original spans. An empty iterator
    /// produces empty text with no mappings; empty fragments still delimit separators.
    pub(crate) fn join(items: impl IntoIterator<Item = Self>, separator: &str) -> Self {
        let mut result = Self::default();
        for (index, item) in items.into_iter().enumerate() {
            if index > 0 {
                result.text.push_str(separator);
            }
            result.push(item);
        }
        result
    }

    /// Appends a valid fragment and rebases its mappings after the current text.
    /// Existing mappings and every original span remain unchanged.
    fn push(&mut self, mut other: Self) {
        let offset = self.text.len();
        for mapping in &mut other.mappings {
            mapping.start += offset;
            mapping.end += offset;
        }
        self.text.push_str(&other.text);
        self.mappings.extend(other.mappings);
    }
}

impl From<LeanString> for Code {
    /// Treats all text as synthetic, without inferring source locations.
    fn from(text: LeanString) -> Self {
        Self {
            text,
            mappings: Vec::new(),
        }
    }
}

impl From<LeanStr> for Code {
    fn from(text: LeanStr) -> Self {
        Self::from(LeanString::from(text))
    }
}

impl From<&str> for Code {
    /// Copies synthetic text without adding expression mappings.
    fn from(text: &str) -> Self {
        text.to_lean_string().into()
    }
}

impl From<&Code> for Code {
    /// Clones text and occurrence mappings without rebasing them.
    fn from(code: &Code) -> Self {
        code.clone()
    }
}

/// Encodes a value as a double-quoted JavaScript string literal using JSON escaping.
///
/// `value` is decoded text, not JavaScript source. The result includes its surrounding
/// quotes and preserves the value when parsed as a JavaScript string. It does not
/// encode HTML delimiters or protect an inline script element's closing tag.
pub(crate) fn js_string(value: &str) -> LeanString {
    serde_json::Value::String(value.into()).to_lean_string()
}

/// Concatenates fragments convertible to `Code`, in argument order, with no separator.
/// String arguments denote synthetic syntax; `Code` arguments retain their mappings.
macro_rules! code {
    ($($part:expr),* $(,)?) => {
        $crate::generated::Code::join([$($crate::generated::Code::from($part)),*], "")
    };
}

pub(crate) use code;
