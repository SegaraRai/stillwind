//! Theme vocabulary augmentation for `stillwind/macro`.
//!
//! [`render_vocabulary_types`] collects utility and variant names from the registry,
//! authored definitions and theme tokens. Sorting and deduplication keep generated
//! declarations stable across all framework entrypoints.

use stillwind_design_system::{
    ThemeIndex, ThemeNamespace, ThemeTokenKind, builtin_utility_names,
    builtin_utility_token_prefixes, builtin_variant_names,
};

/// Renders the whole declaration file for `theme`.
pub(crate) fn render_vocabulary_types(theme: &ThemeIndex) -> String {
    let mut utilities = Vec::new();
    {
        utilities.extend(builtin_utility_names(theme));
        utilities.extend(theme.utilities.iter().map(|utility| utility.name.clone()));
        for token in &theme.tokens {
            let Some((namespace, name)) = token.name.value.trim_start_matches("--").split_once('-')
            else {
                continue;
            };
            for (prefix, expected_namespace) in builtin_utility_token_prefixes(theme) {
                if namespace == expected_namespace {
                    utilities.push(format!("{prefix}-{name}"));
                }
            }
        }
    }
    utilities.sort();
    utilities.dedup();
    let entries = utilities
        .into_iter()
        .map(|utility| format!("    \"{utility}\": true;"))
        .collect::<Vec<_>>()
        .join("\n");
    let mut variants = Vec::new();
    {
        variants.extend(builtin_variant_names(theme));
        variants.extend(theme.variants.iter().map(|variant| variant.name.clone()));
        variants.extend(theme.tokens.iter().filter_map(|token| {
            if let ThemeTokenKind::Token {
                namespace: ThemeNamespace::Breakpoint,
                name,
            } = &token.kind
            {
                Some(name.clone())
            } else {
                None
            }
        }));
    }
    variants.sort_unstable();
    variants.dedup();
    let variants = variants
        .into_iter()
        .map(|variant| format!("    \"{variant}\": true;"))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "// Generated by Stillwind from @theme. Do not edit.\nimport \"stillwind/macro\";\n\ndeclare module \"stillwind/macro\" {{\n  interface StillwindUtilityVocabulary {{\n{entries}\n  }}\n  interface StillwindVariantVocabulary {{\n{variants}\n  }}\n}}\n\nexport {{}};\n"
    )
}

#[cfg(test)]
mod tests {
    use stillwind_source::{CssSourceName, FileId, SourceFile};

    use super::render_vocabulary_types;
    use crate::Compiler;

    #[test]
    fn generates_types_from_the_css_theme_vocabulary() {
        let css = crate::css_fixture::source(
            FileId(2),
            "@theme { --color-accent: red; --spacing-4: 1rem; }",
        )
        .unwrap();
        let theme = Compiler::read_theme(&css, &CssSourceName::from("stillwind.css")).unwrap();
        let types = render_vocabulary_types(&theme);

        assert!(types.contains("declare module \"stillwind/macro\""));
        assert!(!types.contains("stillwind/react"));
        assert!(types.contains("\"bg-accent\": true"));
        assert!(types.contains("\"px-4\": true"));
    }

    #[test]
    fn generates_custom_vocabulary_without_implicit_builtins() {
        let source = SourceFile::new(
            FileId(0),
            None,
            None,
            "@utility brand {color:red}\n@custom-variant active (&.active);",
        )
        .unwrap();
        let theme = Compiler::read_theme(&source, &CssSourceName::from("stillwind.css")).unwrap();
        let types = render_vocabulary_types(&theme);
        assert!(types.contains("\"brand\": true"));
        assert!(types.contains("\"active\": true"));
        assert!(!types.contains("\"flex\": true"));
    }
}
