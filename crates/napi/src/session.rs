/// Failures specific to the stateful bindings.
#[derive(Debug, thiserror::Error)]
pub enum NativeSessionError {
    /// A snapshot was requested before the CSS load completed.
    #[error("CSS load is incomplete")]
    IncompleteCssLoad,
    /// The loader uses a different source ID allocator, so its IDs may conflict with
    /// this session's.
    #[error("CSS loader belongs to another source scope; create it with session.newLoader()")]
    ForeignCssLoader,
    /// Recompiling retained modules against the new stylesheet failed. Watch sessions
    /// keep the previous revision active while reporting this error.
    #[error("CSS reload compilation failed: {message}")]
    ReloadCompilation {
        /// Source-resolved failures for the attempted CSS revision.
        message: String,
    },
    /// CSS supplied for a producer uses a name already generated by the compiler.
    #[error("CSS a producer authors collides with generated names: {message}")]
    AuthoredCssCollision {
        /// Reports name collisions with their source locations.
        message: String,
    },
}

impl From<NativeSessionError> for Error {
    fn from(error: NativeSessionError) -> Self {
        Self::from_reason(error.to_string())
    }
}

/// Uses `sources` to locate errors in `diagnostics` and returns batches and display
/// text. The Node binding uses the text when throwing an error.
///
/// # Errors
///
/// Returns an error if any span cannot be resolved through the project registry.
fn resolve_error_map(
    diagnostics: &BTreeMap<ModuleId, Vec<CompileError>>,
    sources: &SourceRegistry,
) -> napi::Result<(BTreeMap<ModuleId, DiagnosticBatch>, String)> {
    let mut batches = BTreeMap::new();
    let mut lines = Vec::new();
    for (module, errors) in diagnostics {
        let batch = Reporter::collect(errors, &[], sources, LintSettings::default())
            .map_err(|error| Error::from_reason(error.to_string()))?;
        for diagnostic in &batch.diagnostics {
            lines.push(format!(
                "{}: {}",
                module.as_str(),
                diagnostic.display_text()
            ));
        }
        batches.insert(module.clone(), batch);
    }
    Ok((batches, lines.join("\n")))
}

/// One CSS source supplied by the host in one [`NativeDesignSystemLoader::provide`]
/// call.
#[napi(object)]
pub struct NativeCssFileInput {
    /// Request id being answered; `0` is the root source.
    pub id: u32,
    /// The host chooses this name for CSS resolution. The loader compares it as
    /// supplied.
    pub name: String,
    /// Absolute document URI supplied by the host; absent means an internal buffer.
    pub uri: Option<String>,
    /// Exact source name to write into a generated source map.
    pub source_map_source: Option<String>,
    /// Full text of the source.
    pub content: String,
}

/// Loads CSS files supplied by the caller into a design-system snapshot.
///
/// Supply the root source first, then answer each requested ID. The loader reports
/// parse and link errors. If the host cannot read a file, it must report that error
/// and discard the loader.
#[napi]
pub struct NativeDesignSystemLoader {
    loader: DesignSystemLoader,
    options: CompilerOptions,
    snapshot: Option<DesignSystemSnapshot>,
}

#[napi]
impl NativeDesignSystemLoader {
    fn with_sources(
        options: Option<NativeCompilerOptions>,
        sources: SourceRegistry,
    ) -> napi::Result<Self> {
        let options = compiler_options(options)?;
        Ok(Self {
            loader: DesignSystemLoader::new(options.design_system(), sources),
            options,
            snapshot: None,
        })
    }

    /// Creates a loader for the given compiler options.
    #[napi(constructor, strict)]
    pub fn new(options: Option<NativeCompilerOptions>) -> napi::Result<Self> {
        Self::with_sources(options, SourceRegistry::default())
    }

    /// Answers one pending request by calling [`Self::provide_many`] with one file.
    /// An absent URI marks the CSS as an internal buffer without a reportable location.
    #[napi]
    pub fn provide(
        &mut self,
        id: u32,
        name: String,
        content: String,
        uri: Option<String>,
        source_map_source: Option<String>,
    ) -> napi::Result<NativeCssLoadStep> {
        self.provide_many(vec![NativeCssFileInput {
            id,
            name,
            uri,
            source_map_source,
            content,
        }])
    }

    /// Answers any subset of the outstanding requests, in any order.
    ///
    /// Each supplied source is parsed immediately, and its imports appear in the next
    /// step. Other requests can remain unanswered. Unknown or duplicate IDs cause
    /// errors.
    #[napi(strict)]
    pub fn provide_many(
        &mut self,
        files: Vec<NativeCssFileInput>,
    ) -> napi::Result<NativeCssLoadStep> {
        let files = files
            .into_iter()
            .map(|file| {
                let uri = file
                    .uri
                    .map(SourceUri::parse)
                    .transpose()
                    .map_err(|error| Error::from_reason(error.to_string()))?;
                Ok(CssFileInput {
                    id: file.id,
                    name: file.name.as_str().into(),
                    uri,
                    source_map_source: file.source_map_source.map(Into::into),
                    content: file.content.into(),
                })
            })
            .collect::<napi::Result<Vec<_>>>()?;
        match self.loader.provide_many(files) {
            DesignSystemLoadStep::NeedFile(requests) => Ok(NativeCssLoadStep::NeedFile {
                requests: requests
                    .into_iter()
                    .map(|request| NativeCssRequest {
                        id: request.id,
                        importer: request.importer.as_str().to_owned(),
                        specifier: request.specifier,
                    })
                    .collect(),
            }),
            DesignSystemLoadStep::Complete(Ok(snapshot)) => {
                prepare_canonical_index(&snapshot, &self.options);
                let output = NativeCssLoadStep::Complete {
                    revision: snapshot.revision().0.to_string(),
                    resources: snapshot
                        .sources()
                        .resources
                        .iter()
                        .map(|resource| NativeCssResource {
                            placeholder: resource.placeholder.clone(),
                            source_name: resource.source_name.as_str().to_owned(),
                            specifier: resource.specifier.clone(),
                            start: resource.span.start.0,
                            end: resource.span.end.0,
                        })
                        .collect(),
                    sources: snapshot
                        .sources()
                        .sources
                        .iter()
                        .map(|source| source.name.as_str().to_owned())
                        .collect(),
                };
                self.snapshot = Some(snapshot);
                Ok(output)
            }
            DesignSystemLoadStep::Complete(Err(error)) => {
                if let Some(root) = self
                    .loader
                    .root_source()
                    .filter(|source| source.uri().is_some())
                {
                    let compiled =
                        DesignSystemError::Load(error.clone()).into_compile_error(root.full_span());
                    let text = Reporter::collect(
                        std::slice::from_ref(&compiled),
                        &[],
                        self.loader.sources(),
                        LintSettings::default(),
                    )
                    .map_err(|failure| Error::from_reason(failure.to_string()))?
                    .diagnostics
                    .into_iter()
                    .map(|diagnostic| diagnostic.display_text())
                    .collect::<Vec<_>>()
                    .join("\n");
                    Err(Error::from_reason(text))
                } else {
                    Err(Error::from_reason(error.to_string()))
                }
            }
        }
    }

    /// Creates editor queries pinned to this completed design system and its compiler options.
    /// Returns an error while CSS loading is incomplete.
    #[napi]
    pub fn editor_query(&self) -> napi::Result<NativeEditorQuery> {
        Ok(NativeEditorQuery::new(
            self.completed()?,
            self.options.clone(),
        ))
    }
}

impl NativeDesignSystemLoader {
    /// Snapshot of a completed load, or an error naming the missing step.
    fn completed(&self) -> Result<DesignSystemSnapshot, NativeSessionError> {
        self.snapshot
            .clone()
            .ok_or(NativeSessionError::IncompleteCssLoad)
    }
}

/// Adapter for facts already produced by the host's long-lived TS7 service.
///
/// The host pairs its facts with the scans it sent; this adapter only wraps them with
/// the module and asset metadata the domain type requires.
struct ProvidedTypeScriptFacts<'a> {
    /// Host sources in the same order as the scans passed to `update`.
    sources: &'a [HostPreparedSource],
}

impl TypeScriptFactsProvider for ProvidedTypeScriptFacts<'_> {
    fn update(&mut self, scans: &[ModuleScan]) -> TypeFactsUpdate {
        let assets: BTreeMap<_, _> = scans
            .iter()
            .flat_map(|scan| scan.summary.assets.iter())
            .map(|asset| (asset.identity.clone(), asset.metadata.clone()))
            .collect();
        let modules = scans
            .iter()
            .zip(self.sources)
            .map(|(scan, source)| {
                let semantic_revision =
                    Fingerprint::of(format!("{:?}{assets:?}", source.type_facts()));
                (
                    scan.module_id.clone(),
                    TypeFacts {
                        schema: TypeFacts::SCHEMA,
                        module_id: scan.module_id.clone(),
                        source_revision: scan.source_revision.clone(),
                        semantic_revision,
                        facts: source.type_facts().to_vec(),
                        assets: assets.clone(),
                    },
                )
            })
            .collect();
        TypeFactsUpdate {
            modules,
            diagnostics: Vec::new(),
        }
    }
}

/// Mutable project state for one Vite or CLI session.
#[napi]
pub struct NativeProjectSession {
    /// Project session.
    session: ProjectSession,
    /// Host name generators, which are callable only during a host call.
    naming: Option<Rc<NativeNaming>>,
}

#[napi]
impl NativeProjectSession {
    /// Collects local diagnostics from available IR without generating or publishing artifacts.
    /// Type facts may cover only some expressions. Unresolved lowering remains in the reports.
    ///
    /// # Errors
    ///
    /// Returns an error for malformed inputs, duplicate module identities, or invalid report ranges.
    #[napi(strict)]
    pub fn diagnose(
        &self,
        env: Env,
        sources: Vec<NativePreparedSource>,
    ) -> napi::Result<Vec<NativeDiagnosticBatch>> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        let sources = sources
            .into_iter()
            .map(TryInto::try_into)
            .collect::<napi::Result<Vec<HostPreparedSource>>>()?;
        let mut ids = BTreeSet::new();
        for source in &sources {
            if !ids.insert(source.module_id()) {
                return Err(Error::from_reason(format!(
                    "Duplicate Stillwind module identity: {}",
                    source.module_id()
                )));
            }
        }
        let mut registry = self.session.sources().fork_empty();
        let scans = sources
            .iter()
            .map(|source| {
                Ok::<_, Error>(OxcSourceAnalyzer.scan_input(source.input(&mut registry)?))
            })
            .collect::<Result<Vec<_>, _>>()?;
        for source in &self.session.snapshot().sources().sources {
            if source.source.uri().is_some() {
                registry
                    .retain(source.source.clone())
                    .map_err(|error| Error::from_reason(error.to_string()))?;
            }
        }
        let facts = ProvidedTypeScriptFacts { sources: &sources }.update(&scans);
        let compiler = ModuleCompiler::new(self.session.snapshot(), self.session.options().clone());
        scans
            .iter()
            .map(|scan| {
                let analysis =
                    OxcSourceAnalyzer.finalize(scan.clone(), facts.modules.get(&scan.module_id));
                let result = compiler.diagnose(&analysis, self.session.identifiers());
                let batch = Reporter::collect(
                    &result.diagnostics,
                    &result.lint_findings,
                    &registry,
                    result.lint_settings,
                )
                .map_err(|error| Error::from_reason(error.to_string()))?;
                Ok(NativeDiagnosticBatch::new(&scan.module_id, &batch))
            })
            .collect()
    }

    /// Scans a source before checker queries. Fatal failures replace the module's
    /// latest reports and reject its attempted revision without publishing output.
    /// Malformed host transport remains an exception.
    #[napi]
    pub fn scan_source(&mut self, source: NativePreparedSource) -> napi::Result<NativeScanResult> {
        let source = HostPreparedSource::try_from(source)?;
        let module = source.module_id().clone();
        let result = scan_prepared(&source, self.session.sources_mut())?;
        if let SourceScan::Failed { scan, batch } = &result {
            self.session.reject_source_attempt(
                module.clone(),
                scan.source.clone(),
                scan.diagnostics.clone(),
            );
            self.session
                .publish_diagnostic_batch(module.clone(), batch.clone());
        }
        Ok(result.into_binding(&module))
    }

    /// Resolves a known projection or checker failure in the original revision.
    /// Keeps successful watch output and publishes the attempted diagnostic batch.
    /// Rejects malformed document identities or original coordinates.
    #[napi]
    pub fn report_source_failure(
        &mut self,
        failure: NativeSourceFailure,
    ) -> napi::Result<NativeDiagnosticBatch> {
        let (module, source, error) = failure.resolve(self.session.sources_mut())?;
        let diagnostics = vec![error];
        let batch = Reporter::collect(
            &diagnostics,
            &[],
            self.session.sources(),
            LintSettings::default(),
        )
        .map_err(|error| Error::from_reason(error.to_string()))?;
        let result = NativeDiagnosticBatch::new(&module, &batch);
        self.session
            .reject_source_attempt(module.clone(), source, diagnostics);
        self.session.publish_diagnostic_batch(module, batch);
        Ok(result)
    }

    /// Returns the latest attempted diagnostics for every retained module.
    #[napi]
    pub fn diagnostic_batches(&self) -> Vec<NativeDiagnosticBatch> {
        self.session
            .diagnostic_batches()
            .iter()
            .map(|(module, batch)| NativeDiagnosticBatch {
                module: module.as_str().to_owned(),
                reports: batch
                    .diagnostics
                    .iter()
                    .cloned()
                    .map(BindingReport::from)
                    .collect(),
            })
            .collect()
    }

    /// Creates a session from a completed `loader`. If `watch` is true, a failed reload
    /// keeps the last successful revision.
    ///
    /// `mode` selects development behavior only when it equals `"development"`.
    /// Other values, including no value, select release behavior. If a host-supplied
    /// name is rejected, development mode reports a lint finding and release mode
    /// fails compilation.
    ///
    /// `naming` supplies an optional name generator for each family. Returning
    /// `undefined` keeps the compiler's name. Each function must return the same name
    /// for the same request. Change `naming_revision` when changing these functions
    /// so cached output from the old generators is not reused.
    ///
    /// # Errors
    ///
    /// Returns an error if the loader is incomplete or name generators cannot be
    /// initialized.
    #[napi(constructor)]
    #[allow(clippy::needless_pass_by_value)] // Node-API decodes JavaScript strings as owned Rust values.
    pub fn new(
        loader: &NativeDesignSystemLoader,
        watch: bool,
        mode: Option<String>,
        naming: Option<NativeIdentifierNaming>,
    ) -> napi::Result<Self> {
        let identifier_mode = match mode.as_deref() {
            Some("development") => IdentifierMode::Development,
            _ => IdentifierMode::Release,
        };
        let naming = NativeNaming::from_js(naming)?;
        let identifiers = Identifiers::new(
            naming
                .as_ref()
                .map(|naming| naming.clone() as Rc<dyn IdentifierGenerator>),
            identifier_mode,
        );
        let snapshot = loader.completed()?;
        let session = ProjectSession::new(
            snapshot.clone(),
            loader.loader.sources(),
            if watch {
                SessionMode::Watch
            } else {
                SessionMode::Build
            },
            loader.options.clone(),
            identifiers,
        );
        Ok(Self { session, naming })
    }

    /// Creates a CSS loader that shares this session's source ID allocator.
    /// Use it for reloads to avoid conflicts between CSS and script file IDs.
    #[napi]
    pub fn new_loader(
        &self,
        options: Option<NativeCompilerOptions>,
    ) -> napi::Result<NativeDesignSystemLoader> {
        NativeDesignSystemLoader::with_sources(options, self.session.sources().fork_empty())
    }

    /// Publishes a reloaded design system and reports what changed.
    ///
    /// `loader` must be complete and created by this session.
    /// If recompilation fails, the error lists the failing modules. Watch mode keeps
    /// the previous revision. Build mode publishes the new revision without the failed
    /// modules before returning this error.
    #[napi]
    pub fn reload(
        &mut self,
        env: Env,
        loader: &NativeDesignSystemLoader,
    ) -> napi::Result<NativeReload> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        if !self
            .session
            .sources()
            .shares_ids_with(loader.loader.sources())
        {
            return Err(NativeSessionError::ForeignCssLoader.into());
        }
        let snapshot = loader.completed()?;
        let update = self
            .session
            .reload(Ok(snapshot.clone()), loader.options.clone())
            .map_err(|error| Error::from_reason(error.to_string()))?;
        if !update.diagnostics.is_empty() {
            let sources = self
                .session
                .diagnostic_sources_for(&snapshot)
                .map_err(|error| Error::from_reason(error.to_string()))?;
            let (mut batches, message) = resolve_error_map(&update.diagnostics, &sources)?;
            let modules = self.session.analyses().keys().cloned().collect::<Vec<_>>();
            for module in modules {
                let batch = batches.remove(&module).unwrap_or_default();
                self.session.publish_diagnostic_batch(module, batch);
            }
            self.session
                .prune_sources()
                .map_err(|error| Error::from_reason(error.to_string()))?;
            return Err(NativeSessionError::ReloadCompilation { message }.into());
        }
        Self::refresh_batches(&mut self.session)?;
        Ok(NativeReload {
            css_changed: update.css_changed,
            transformed_modules: update
                .transformed_modules
                .into_iter()
                .map(ModuleId::into_string)
                .collect(),
        })
    }

    /// Renders the complete stylesheet for the current revision.
    #[napi]
    pub fn css(&self, env: Env) -> napi::Result<String> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        self.session
            .css()
            .map_err(|error| Error::from_reason(error.to_string()))
    }

    /// Returns CSS and producer revisions for the modules selected by the host.
    ///
    /// `input` selects registered producers, coverage, and document or carrier
    /// placement. Complete coverage requires target and revision strings with
    /// non-whitespace text. The plan also includes modules required by composition.
    /// The session is unchanged.
    ///
    /// Source maps are included by default. Passing false for the second argument
    /// leaves the sources and entries empty in the plan's map and each part's map. This
    /// avoids copying source text and mappings into JavaScript when the host does not
    /// need them. CSS, ordering, owners, and producer revisions are the same with
    /// either setting.
    ///
    /// # Errors
    ///
    /// Returns an error if a producer is missing or no longer matches its analysis,
    /// composition or CSS is invalid, or complete coverage has invalid identifiers.
    /// Conversion fails if a value exceeds its 32-bit range. With maps enabled,
    /// conversion also fails if a source location cannot be resolved.
    #[napi(strict)]
    pub fn plan_stylesheet(
        &self,
        env: Env,
        input: NativeStylesheetSelection,
        include_source_maps: Option<bool>,
    ) -> napi::Result<NativeStylesheetPlan> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        let include_source_maps = include_source_maps.unwrap_or(true);
        let coverage = match input.coverage {
            NativeCoverage::Observed => StylesheetCoverage::Observed,
            NativeCoverage::Complete { target, revision } => {
                StylesheetCoverage::Complete { target, revision }
            }
        };
        let placement = match input.placement {
            NativeStylesheetPlacement::Document => StylesheetPlacement::Document,
            NativeStylesheetPlacement::Carrier => StylesheetPlacement::Carrier,
        };
        let plan = self
            .session
            .plan_stylesheet(
                StylesheetSelection {
                    modules: input.modules.into_iter().map(Into::into).collect(),
                    coverage,
                },
                placement,
            )
            .map_err(|error| Error::from_reason(error.to_string()))?;
        let coverage = match plan.coverage {
            StylesheetCoverage::Observed => NativeCoverage::Observed,
            StylesheetCoverage::Complete { target, revision } => {
                NativeCoverage::Complete { target, revision }
            }
        };
        Ok(NativeStylesheetPlan {
            parts: plan
                .parts
                .into_iter()
                .map(|part| {
                    Ok(NativeStylesheetPart {
                        source_map: stylesheet_locations(if include_source_maps {
                            &part.mappings
                        } else {
                            &[]
                        })?,
                        slot: u32::try_from(part.slot)
                            .map_err(|_| Error::from_reason("Stylesheet slot exceeds 32 bits"))?,
                        sequence: u32::try_from(part.sequence).map_err(|_| {
                            Error::from_reason("Stylesheet sequence exceeds 32 bits")
                        })?,
                        key: part.key.0,
                        css: part.css,
                        producers: part
                            .producers
                            .into_iter()
                            .map(ModuleId::into_string)
                            .collect(),
                    })
                })
                .collect::<napi::Result<_>>()?,
            css: plan.css,
            source_map: stylesheet_locations(if include_source_maps {
                &plan.mappings
            } else {
                &[]
            })?,
            resources: plan.resources.into_iter().map(Into::into).collect(),
            coverage,
            placement: input.placement,
            design_system: plan.design_system.0,
            producers: plan
                .producers
                .into_iter()
                .map(|(module, key)| NativeStylesheetProducer {
                    module: module.into_string(),
                    source_revision: key.source_revision.0,
                    semantic_revision: key.semantic_revision.map(|revision| revision.0),
                    compiler_version: key.compiler_version,
                    compiler_options: key.compiler_options.0,
                    analysis_revision: key.analysis_revision.0,
                })
                .collect(),
        })
    }

    /// Stable document CSS without a source map, independent of visited JS modules.
    #[napi]
    pub fn base_css(&self, env: Env) -> napi::Result<String> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        StylesheetRenderer::new(
            &self.session.snapshot(),
            self.session.options(),
            self.session.identifiers(),
        )
        .render_stylesheet("")
        .map_err(|error| Error::from_reason(error.to_string()))
    }

    /// Base document CSS with a source map, for review tooling.
    #[napi]
    pub fn base_css_with_map(&self, env: Env) -> napi::Result<NativeStylesheetOutput> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        let output = StylesheetRenderer::new(
            &self.session.snapshot(),
            self.session.options(),
            self.session.identifiers(),
        )
        .render_mapped_stylesheet(&MappedStylesheet::default(), StylesheetPlacement::Document)
        .map_err(|error| Error::from_reason(error.to_string()))?;
        Ok(NativeStylesheetOutput {
            css: output.css,
            source_map: stylesheet_locations(&output.mappings)?,
        })
    }

    /// Complete CSS for one producer, safe to transport across loader workers.
    #[napi]
    #[allow(clippy::needless_pass_by_value)] // Node-API decodes JavaScript strings as owned Rust values.
    pub fn module_css(&self, env: Env, module: String) -> napi::Result<String> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        self.session
            .plan_stylesheet(
                StylesheetSelection {
                    modules: [module.into()].into(),
                    coverage: StylesheetCoverage::Observed,
                },
                StylesheetPlacement::Carrier,
            )
            .map(|output| output.css)
            .map_err(|error| Error::from_reason(error.to_string()))
    }

    /// Removes a producer, returning whether it was registered.
    #[napi]
    #[allow(clippy::needless_pass_by_value)] // Node-API decodes JavaScript strings as owned Rust values.
    pub fn remove(&mut self, module: String) -> napi::Result<bool> {
        let removed = self.session.remove_module(&ModuleId::from(module));
        Self::refresh_batches(&mut self.session)?;
        Ok(removed)
    }

    /// Reserves the names one producer's own stylesheet uses, or forgets it when `css` is absent.
    ///
    /// The design system's CSS is already reserved; a stylesheet a producer authors itself is not
    /// part of it, so the host supplies its text here. Returns the producers whose published
    /// artifacts now collide with an authored name, which the host recompiles or drops.
    #[napi]
    #[allow(clippy::needless_pass_by_value)] // Node-API decodes JavaScript strings as owned Rust values.
    pub fn reserve_authored_css(
        &mut self,
        module: String,
        css: Option<String>,
    ) -> napi::Result<()> {
        let reported = match css {
            Some(css) => self
                .session
                .reserve_authored_css(&ModuleId::from(module), &css),
            None => self.session.forget_authored_css(&ModuleId::from(module)),
        };
        if reported.is_empty() {
            Self::refresh_batches(&mut self.session)?;
            return Ok(());
        }
        let sources = self
            .session
            .diagnostic_sources()
            .map_err(|error| Error::from_reason(error.to_string()))?;
        let (batches, message) = resolve_error_map(&reported, &sources)?;
        for (module, batch) in batches {
            self.session.publish_diagnostic_batch(module, batch);
        }
        self.session
            .prune_sources()
            .map_err(|error| Error::from_reason(error.to_string()))?;
        Err(NativeSessionError::AuthoredCssCollision { message }.into())
    }

    /// Scans and compiles `sources` against the current session snapshot in one
    /// transaction. Sources must have distinct module identities and describe valid
    /// editable or projected inputs. `env` provides the naming callback context. Every
    /// source is compiled; `producer`, when present, selects its output after
    /// successful publication.
    ///
    /// Success publishes all artifacts and refreshes diagnostic batches for current
    /// consumers. Returned outputs use the final graph, independently of source order.
    /// A compilation failure records attempted analyses and reports, retains last good
    /// watch artifacts, and returns outputs for every attempted source without
    /// publishing the transaction. Consumer checks then exclude artifacts with stale
    /// analyses.
    ///
    /// # Errors
    ///
    /// Returns an error for invalid input conversion, duplicate identities, a producer
    /// absent from the inputs, or unavailable diagnostic sources or transforms. Report
    /// errors can occur after failed attempted analyses have been recorded.
    #[napi(strict)]
    #[allow(clippy::needless_pass_by_value)] // Node-API decodes JavaScript strings as owned Rust values.
    pub fn compile(
        &mut self,
        env: Env,
        sources: Vec<NativePreparedSource>,
        producer: Option<String>,
    ) -> napi::Result<ProjectBindingOutput> {
        let _naming = self.naming.as_ref().map(|naming| naming.enter(&env));
        let producer = producer.map(ModuleId::from);
        let sources = sources
            .into_iter()
            .map(TryInto::try_into)
            .collect::<napi::Result<Vec<HostPreparedSource>>>()?;
        let mut module_ids = BTreeSet::new();
        for source in &sources {
            if !module_ids.insert(source.module_id()) {
                return Err(Error::from_reason(format!(
                    "Duplicate Stillwind module identity: {}",
                    source.module_id()
                )));
            }
        }
        if let Some(producer) = &producer
            && !sources.iter().any(|source| source.module_id() == producer)
        {
            return Err(Error::from_reason(format!(
                "Unknown Stillwind producer: {producer}"
            )));
        }
        let mut transaction = self.session.clone();
        let scans: Vec<_> = sources
            .iter()
            .map(|source| {
                Ok::<_, Error>(
                    OxcSourceAnalyzer.scan_input(source.input(transaction.sources_mut())?),
                )
            })
            .collect::<Result<_, _>>()?;
        let facts = ProvidedTypeScriptFacts { sources: &sources }.update(&scans);
        let analyses: Vec<_> = scans
            .iter()
            .map(|scan| {
                OxcSourceAnalyzer.finalize(scan.clone(), facts.modules.get(&scan.module_id))
            })
            .collect();
        let snapshot = self.session.snapshot();
        let mut modules = Vec::new();
        let mut attempted = Vec::new();
        let diagnostic_sources = transaction
            .diagnostic_sources()
            .map_err(|error| Error::from_reason(error.to_string()))?;
        for module_analysis in ModuleAnalysis::attach_asset_support_batch(&analyses) {
            let module_id = module_analysis.module_id.clone();
            let source = module_analysis.source.clone();
            let update = transaction.update_module(module_analysis.clone());
            attempted.push(module_analysis);
            let result = if update.diagnostics.is_empty() {
                transaction
                    .artifacts()
                    .get(&module_id)
                    .map(|artifact| artifact.to_module_output())
                    .unwrap_or_default()
            } else {
                CompileResult {
                    diagnostics: update.diagnostics,
                    lint_settings: self.session.options().lint_settings(&snapshot),
                    ..CompileResult::default()
                }
            };
            let (output, batch) = binding_output_with_batch(result, &source, &diagnostic_sources)?;
            transaction.publish_diagnostic_batch(module_id.clone(), batch);
            modules.push(ProjectModuleOutput::new(module_id, output));
        }
        if modules.iter().all(|module| module.diagnostics.is_empty()) {
            Self::refresh_batches(&mut transaction)?;
            let final_sources = transaction
                .diagnostic_sources()
                .map_err(|error| Error::from_reason(error.to_string()))?;
            modules = attempted
                .iter()
                .map(|analysis| {
                    let artifact = transaction
                        .current_artifact(&analysis.module_id)
                        .ok_or_else(|| {
                            Error::from_reason("Successful compilation has no current artifact")
                        })?;
                    let (output, _) = binding_output_with_batch(
                        artifact.to_module_output(),
                        &analysis.source,
                        &final_sources,
                    )?;
                    Ok(ProjectModuleOutput::new(analysis.module_id.clone(), output))
                })
                .collect::<napi::Result<Vec<_>>>()?;
            self.session = transaction;
            if let Some(producer) = &producer {
                modules.retain(|module| module.module_id == producer.as_str());
            }
        } else {
            self.session.reject_updates(attempted);
            self.session.retain_attempted_sources(&transaction);
            self.session.retain_attempted_diagnostics(&transaction);
            Self::refresh_batches(&mut self.session)?;
        }
        Ok(ProjectBindingOutput { modules })
    }
}

impl NativeProjectSession {
    /// Updates diagnostic batches for artifacts that match the latest analyses in
    /// `session`. The caller must update the graph and composition findings first.
    /// Output kept after a watch failure is skipped if its analysis changed, keeping
    /// the failure report. A successful call removes source snapshots that are no
    /// longer referenced.
    ///
    /// This method copies diagnostics, lint settings, and transforms into binding
    /// results. It skips CSS, classes, and resources to avoid copying unchanged output.
    /// Transforms are needed because creating a report also checks the source edits.
    ///
    /// # Errors
    ///
    /// Returns an error when a required source snapshot or diagnostic span cannot be
    /// resolved, or source pruning fails. Batches published before an error remain.
    fn refresh_batches(session: &mut ProjectSession) -> napi::Result<()> {
        let refreshed = session
            .analyses()
            .iter()
            .filter_map(|(module, analysis)| {
                session.current_artifact(module).map(|artifact| {
                    (
                        module.clone(),
                        analysis.source.clone(),
                        CompileResult {
                            diagnostics: artifact.diagnostics.clone(),
                            lint_findings: artifact.lint_findings.clone(),
                            lint_settings: artifact.lint_settings.clone(),
                            transforms: artifact.code_transforms.clone(),
                            ..CompileResult::default()
                        },
                    )
                })
            })
            .collect::<Vec<_>>();
        let diagnostic_sources = session
            .diagnostic_sources()
            .map_err(|error| Error::from_reason(error.to_string()))?;
        for (module, source, result) in refreshed {
            let (_, batch) = binding_output_with_batch(result, &source, &diagnostic_sources)?;
            session.publish_diagnostic_batch(module, batch);
        }
        session
            .prune_sources()
            .map_err(|error| Error::from_reason(error.to_string()))?;
        Ok(())
    }
}
